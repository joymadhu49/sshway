const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { isIP } = require('node:net');

const includeLine = 'Include ~/.ssh/sshway/config';
const header = '# Generated by sshway. Edit hosts with the sshway command.\n';

function locations() {
  const home = os.homedir();
  if (!home || !path.isAbsolute(home)) throw new Error('Cannot locate your home directory.');
  const ssh = path.join(home, '.ssh');
  const dir = path.join(ssh, 'sshway');
  return {
    ssh,
    dir,
    main: path.join(ssh, 'config'),
    data: path.join(dir, 'hosts.json'),
    config: path.join(dir, 'config'),
    bin: path.join(home, '.local', 'bin'),
  };
}

function rejectNonFile(file) {
  try {
    if (!fs.lstatSync(file).isFile()) throw new Error(`${file} is not a regular file.`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

function ensureDirectory(dir, mode) {
  fs.mkdirSync(dir, { recursive: true, mode });
  if (!fs.lstatSync(dir).isDirectory()) throw new Error(`${dir} is not a directory.`);
}

function atomicWrite(file, content, mode) {
  rejectNonFile(file);
  const temp = path.join(path.dirname(file), `.${path.basename(file)}.${process.pid}.${crypto.randomBytes(6).toString('hex')}`);
  try {
    fs.writeFileSync(temp, content, { encoding: 'utf8', flag: 'wx', mode });
    fs.renameSync(temp, file);
  } finally {
    if (fs.existsSync(temp)) fs.unlinkSync(temp);
  }
}

function validName(name) {
  if (typeof name !== 'string' || !/^[a-z][a-z0-9_-]{0,62}$/.test(name)) {
    throw new Error('Name must start with a lowercase letter and contain only lowercase letters, digits, _ or -.');
  }
  return name;
}

function validHost(host) {
  if (typeof host !== 'string' || !(isIP(host) || (/^[a-zA-Z0-9][a-zA-Z0-9.-]*$/.test(host) && !host.includes('..')))) {
    throw new Error('Host must be a DNS name or IP address.');
  }
  return host;
}

function parseDestination(destination) {
  if (typeof destination !== 'string') throw new Error('Expected [user@]host.');
  const split = destination.lastIndexOf('@');
  const user = split < 0 ? null : destination.slice(0, split);
  const rawHost = destination.slice(split + 1);
  const host = rawHost.startsWith('[') && rawHost.endsWith(']') ? rawHost.slice(1, -1) : rawHost;
  if (user && !/^[a-zA-Z_][a-zA-Z0-9_.-]*\$?$/.test(user)) throw new Error('Invalid SSH user name.');
  if (split >= 0 && !user) throw new Error('Invalid SSH user name.');
  validHost(host);
  return { user, host };
}

function validateOptions(options) {
  const result = {};
  if (options.port !== undefined) {
    if (!/^\d+$/.test(String(options.port)) || Number(options.port) < 1 || Number(options.port) > 65535) {
      throw new Error('Port must be between 1 and 65535.');
    }
    result.port = Number(options.port);
  }
  if (options.identity !== undefined) {
    if (typeof options.identity !== 'string' || !/^(?:~\/|\/)[a-zA-Z0-9_./+-]+$/.test(options.identity) || options.identity.includes('..')) {
      throw new Error('Identity must be an absolute path or ~/ path without spaces.');
    }
    result.identity = options.identity;
  }
  return result;
}

function list() {
  const { data } = locations();
  rejectNonFile(data);
  if (!fs.existsSync(data)) return {};
  const hosts = JSON.parse(fs.readFileSync(data, 'utf8'));
  if (!hosts || Array.isArray(hosts) || typeof hosts !== 'object') throw new Error('Invalid sshway hosts file.');
  for (const [name, item] of Object.entries(hosts)) {
    validName(name);
    if (!item || typeof item !== 'object' || Array.isArray(item)) throw new Error('Invalid sshway host entry.');
    validHost(item.host);
    if (item.user !== null && item.user !== undefined && !/^[a-zA-Z_][a-zA-Z0-9_.-]*\$?$/.test(item.user)) throw new Error('Invalid SSH user name in hosts file.');
    validateOptions(item);
  }
  return hosts;
}

function render(hosts) {
  return header + Object.entries(hosts).sort(([a], [b]) => a.localeCompare(b)).map(([name, item]) => {
    const lines = [`Host ${name}`, `    HostName ${item.host}`];
    if (item.user) lines.push(`    User ${item.user}`);
    if (item.port) lines.push(`    Port ${item.port}`);
    if (item.identity) lines.push(`    IdentityFile ${item.identity}`, '    IdentitiesOnly yes');
    return `${lines.join('\n')}\n`;
  }).join('\n');
}

function save(hosts) {
  const files = locations();
  ensureDirectory(files.ssh, 0o700);
  ensureDirectory(files.dir, 0o700);
  rejectNonFile(files.main);
  const current = fs.existsSync(files.main) ? fs.readFileSync(files.main, 'utf8') : '';
  const lines = current.split(/\r?\n/);
  if (!lines.some(line => line.trim() === includeLine)) {
    atomicWrite(files.main, `${includeLine}\n\n${current}`, 0o600);
  }
  atomicWrite(files.config, render(hosts), 0o600);
  atomicWrite(files.data, `${JSON.stringify(hosts, null, 2)}\n`, 0o600);
}

function add(name, destination, options = {}) {
  validName(name);
  const hosts = list();
  if (Object.hasOwn(hosts, name)) throw new Error(`${name} already exists. Remove it first.`);
  hosts[name] = { ...parseDestination(destination), ...validateOptions(options) };
  save(hosts);
}

function wrapper(name) {
  return `#!/bin/sh\n# sshway managed shortcut\nexec ssh ${name} "$@"\n`;
}

function shortcut(name) {
  validName(name);
  if (!Object.hasOwn(list(), name)) throw new Error('Unknown host. Use sshway list.');
  const files = locations();
  ensureDirectory(files.bin, 0o755);
  const target = path.join(files.bin, name);
  rejectNonFile(target);
  const expected = wrapper(name);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') !== expected) throw new Error(`${target} already exists.`);
  const onPath = (process.env.PATH || '').split(path.delimiter).some(dir => path.resolve(dir || '.') === files.bin);
  for (const dir of (process.env.PATH || '').split(path.delimiter)) {
    if (!dir) continue;
    const candidate = path.join(dir, name);
    if (candidate !== target && fs.existsSync(candidate)) throw new Error(`${name} already exists on PATH at ${candidate}.`);
  }
  atomicWrite(target, expected, 0o755);
  return { path: target, onPath };
}

function remove(name) {
  validName(name);
  const hosts = list();
  if (!Object.hasOwn(hosts, name)) throw new Error('Unknown host. Use sshway list.');
  const target = path.join(locations().bin, name);
  rejectNonFile(target);
  delete hosts[name];
  save(hosts);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === wrapper(name)) fs.unlinkSync(target);
}

module.exports = { add, list, remove, shortcut };
